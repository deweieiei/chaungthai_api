--  ใหม่: 1 อีเมล = ได้ 2 บัญชีแยกกัน (employer / worker) คนละ user_id
--        แยกโปรไฟล์ แชท งาน รายการโปรด สมบูรณ์ · ล็อกอินคนละอัน
--        อนุญาตให้ใช้อีเมล + รหัสผ่านเดียวกันได้
--
--  กุญแจสำคัญ: UNIQUE ย้ายจาก (user_email) → (user_email, user_account_type)
-- ============================================================

USE chaungthai;

-- ------------------------------------------------------------
--  1) เพิ่มคอลัมน์ประเภทบัญชี
--     ค่าเริ่มต้น employer — บัญชีเก่าทั้งหมดถือเป็นฝั่งผู้ว่าจ้างก่อน
-- ------------------------------------------------------------
ALTER TABLE user_chaungthai
  ADD COLUMN user_account_type ENUM('employer','worker') NOT NULL DEFAULT 'employer'
    COMMENT 'ฝั่งของบัญชี: employer=ผู้ว่าจ้าง / worker=ช่าง — คนละบัญชีกันแม้อีเมลเดียวกัน'
    AFTER user_role;

-- ------------------------------------------------------------
--  2) บัญชีที่มีโปรไฟล์ช่างอยู่แล้ว = ฝั่งช่าง
--     (ต้องทำก่อนเปลี่ยน UNIQUE ไม่งั้นข้อมูลเดิมจะจัดฝั่งผิด)
-- ------------------------------------------------------------
UPDATE user_chaungthai u
  JOIN worker_chaungthai w ON w.worker_user_id = u.user_id
   SET u.user_account_type = 'worker';

-- ------------------------------------------------------------
--  3) ย้าย UNIQUE: อีเมลซ้ำได้ ถ้าคนละฝั่ง
-- ------------------------------------------------------------
ALTER TABLE user_chaungthai
  DROP INDEX user_email,
  ADD UNIQUE KEY uniq_email_account_type (user_email, user_account_type),
  ADD INDEX idx_account_type (user_account_type);
